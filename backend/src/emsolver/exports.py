    t = r.get("tiles", {})
    e = html.escape
    banner = {"met_verified": "Goal met and verified", "verified_not_met": "Verified, goal not met"}.get(
        r["status"], "Not verified")
    checks = "".join(f"<tr><td>{e(c['name'])}</td><td>{e(c['result'])}</td><td>{'✓ Pass' if c['passed'] else '✕ Fail'}</td></tr>"
                     for c in (r.get("verification") or {}).get("checks", []))
    fixes = "".join(f"<li>{e(f['change'])}: {e(f['reason'])}</li>" for f in r.get("fixes", [])) or "<li>None</li>"
    designs = "".join(f"<li>{e(d['label'])} {d['from']} → {d['to']} {d['unit']}: {e(d['rationale'])}</li>"
                      for d in r.get("design_history", [])) or "<li>None</li>"
